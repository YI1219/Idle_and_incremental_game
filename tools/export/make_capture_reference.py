#!/usr/bin/env python3
"""Derive tools/export/capture_reference.gd from tools/art/capture_lookdev.gd.

The lookdev capture tool is fixed at 2560x1440 and its extra cameras live in a
chain of subclass scripts under art/lookdev/. The runtime's first gate is
3024x1964, so the reference frames it is compared against need that size and
all twelve review cameras in one place. This writes a copy of the tool with
only those two things changed. Run from the repository root:

    python3 tools/export/make_capture_reference.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "tools/art/capture_lookdev.gd"
TARGET = ROOT / "tools/export/capture_reference.gd"

CAMERAS = [
    ("game", (0, -1), 21, 16, 27),
    ("whole", (-2, -1), 32, 16, 30),
    ("reverse", (-2, -1), 32, 196, 30),
    ("close", (-10, -5), 13, 16, 30),
    ("cliff_close", (-8, 6), 10, 16, 20),
    ("side_106", (-2, -1), 32, 106, 30),
    ("side_286", (-2, -1), 32, 286, 30),
    ("foot_front", (-8, 6), 13, 16, 24),
    ("foot_reverse", (-2, -1), 17, 196, 18),
    ("overview", (-2, -1), 32, 16, 62),
    ("terrace_close", (-3, -2), 12.5, 28, 26),
    ("outer_hull", (3, 4), 13.5, 344, 18),
]


def main() -> None:
    text = SOURCE.read_text(encoding="utf-8")
    size = "const SIZE := Vector2i(2560, 1440)"
    assert text.count(size) == 1, "size constant not found exactly once"
    text = text.replace(size, "const SIZE := Vector2i(3024, 1964)")
    begin = "\t_frame(Vector2(0, -1), 21, 16, 27)\n"
    end = "\tvar unchanged: bool = initial_data =="
    assert text.count(begin) == 1 and text.count(end) == 1, "capture block markers not found exactly once"
    block = "".join(
        f"\t_frame(Vector2({cx}, {cz}), {height}, {yaw}, {pitch})\n\tawait _capture(\"{name}\", progress)\n"
        for name, (cx, cz), height, yaw, pitch in CAMERAS
    )
    text = text[: text.index(begin)] + block + text[text.index(end):]
    header = "## Deterministic native 2K evidence from the sole playable scene. No user layout IO."
    assert text.count(header) == 1, "header not found"
    text = text.replace(
        header,
        "## GENERATED by tools/export/make_capture_reference.py from tools/art/capture_lookdev.gd.\n"
        "## Reference frames of the frozen Godot project at the runtime's first gate size (3024x1964),\n"
        "## all twelve review cameras. godot --path . --script tools/export/capture_reference.gd -- --out=<new-dir>",
    )
    TARGET.write_text(text, encoding="utf-8")
    print("wrote", TARGET, "cameras", len(CAMERAS))


if __name__ == "__main__":
    main()
